// Generates the third-party license files for everything the desktop app ships:
//
//   THIRD_PARTY_LICENSES.md          every Rust crate linked into the app and every npm
//                                     runtime dependency, with their license and notice
//                                     texts (deduplicated)
//   src/app/thirdPartyComponents.json name, version and license of each, for the
//                                     in-app licenses dialog
//
// Run after changing dependencies:  node scripts/third-party-licenses.mjs
// CI runs it with --check and fails when the files are out of date.
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const check = process.argv.includes("--check");
const LICENSE_FILE = /^(licen[cs]e|copying|notice|copyright|unlicense)([-._].*)?$/i;

function licenseFiles(dir, stopAt) {
  // Crates in a Git workspace keep their license files at the workspace root.
  for (let d = dir, depth = 0; d && depth < 4; d = dirname(d), depth++) {
    const found = readdirSync(d)
      .filter((f) => LICENSE_FILE.test(f) && statSync(join(d, f)).isFile())
      .sort()
      .map((f) => ({
        file: f,
        text: readFileSync(join(d, f), "utf8").replace(/\r\n/g, "\n").trim(),
      }));
    if (found.length > 0 || d === stopAt) return found;
  }
  return [];
}

/** `git+https://host/repo?rev=…#<commit>` as a link to that commit's tree. */
function gitSource(source) {
  const match = /^git\+([^?#]+)(?:\?[^#]*)?#([0-9a-f]+)$/.exec(source ?? "");
  return match ? `${match[1].replace(/\.git$/, "")}/tree/${match[2]}` : null;
}

// Rust: the normal (non-dev, non-build) dependency graph of the app on Windows and in
// general, which is what links into the shipped binary.
const metadata = JSON.parse(
  execFileSync("cargo", ["metadata", "--format-version", "1", "--locked"], {
    cwd: join(root, "src-tauri"),
    maxBuffer: 256 * 1024 * 1024,
    encoding: "utf8",
  }),
);
const nodes = new Map(metadata.resolve.nodes.map((n) => [n.id, n]));
const shipped = new Set();
const stack = [...metadata.workspace_members];
while (stack.length > 0) {
  const id = stack.pop();
  if (shipped.has(id)) continue;
  shipped.add(id);
  for (const dep of nodes.get(id)?.deps ?? []) {
    const linked = dep.dep_kinds.some(
      (k) =>
        k.kind === null &&
        (k.target === null || /windows|not\(target_arch = "wasm32"\)/.test(k.target)),
    );
    if (linked) stack.push(dep.pkg);
  }
}
const components = metadata.packages
  .filter((p) => shipped.has(p.id) && !metadata.workspace_members.includes(p.id))
  .map((p) => ({
    ecosystem: "Rust crate",
    name: p.name,
    version: p.version,
    license: p.license ?? "See license file",
    source: gitSource(p.source) ?? p.repository ?? `https://crates.io/crates/${p.name}`,
    files: licenseFiles(dirname(p.manifest_path)),
  }));

// npm: runtime dependencies bundled into the web view code.
const pkg = JSON.parse(readFileSync(join(root, "package.json"), "utf8"));
const lock = JSON.parse(readFileSync(join(root, "package-lock.json"), "utf8"));
const npmSeen = new Set();
const npmStack = Object.keys(pkg.dependencies ?? {});
while (npmStack.length > 0) {
  const name = npmStack.pop();
  if (npmSeen.has(name)) continue;
  npmSeen.add(name);
  const entry = lock.packages[`node_modules/${name}`];
  if (!entry) continue;
  npmStack.push(...Object.keys(entry.dependencies ?? {}));
  const dir = join(root, "node_modules", name);
  const meta = JSON.parse(readFileSync(join(dir, "package.json"), "utf8"));
  const repo = typeof meta.repository === "string" ? meta.repository : meta.repository?.url;
  components.push({
    ecosystem: "npm package",
    name,
    version: entry.version,
    license: entry.license ?? meta.license ?? "See license file",
    source: repo?.replace(/^git\+/, "") ?? `https://www.npmjs.com/package/${name}`,
    files: existsSync(dir) ? licenseFiles(dir, dir) : [],
  });
}
components.sort(
  (a, b) =>
    a.ecosystem.localeCompare(b.ecosystem) ||
    a.name.localeCompare(b.name) ||
    a.version.localeCompare(b.version),
);

const texts = new Map();
const lines = [
  "# Third-party licenses",
  "",
  "<!-- Generated by scripts/third-party-licenses.mjs. Do not edit by hand. -->",
  "",
  "ArchCompose is licensed under the GNU Affero General Public License v3.0 only (see",
  "`LICENSE`). The desktop app includes the components below, each under its own license.",
  "Where a component offers a choice of licenses, ArchCompose uses it under the first",
  "license listed that is compatible with the AGPL-3.0; the MIT license is used for",
  "components licensed `MIT OR Apache-2.0`. Attribution for PhotoCraft and the assets it",
  "contributes is in `THIRD_PARTY_NOTICES.md`.",
  "",
  "## Components",
  "",
  "| Component | Version | License | Source | License text |",
  "| --- | --- | --- | --- | --- |",
];
for (const c of components) {
  const refs = c.files.map((f) => {
    const hash = createHash("sha256").update(f.text).digest("hex").slice(0, 12);
    if (!texts.has(hash)) texts.set(hash, { text: f.text, file: f.file, users: [] });
    texts.get(hash).users.push(`${c.name} ${c.version}`);
    return `[${f.file}](#text-${hash})`;
  });
  lines.push(
    `| ${c.name} | ${c.version} | ${c.license.replace(/\|/g, "\\|")} | ${c.source} | ${refs.join(", ") || "Declared in package metadata"} |`,
  );
}
lines.push("", "## License and notice texts", "");
for (const [hash, t] of texts) {
  lines.push(
    `### <a id="text-${hash}"></a>${t.file}`,
    "",
    `Used by: ${t.users.join(", ")}`,
    "",
    "```text",
    t.text.replace(/```/g, "'''"),
    "```",
    "",
  );
}

const outputs = [
  [join(root, "THIRD_PARTY_LICENSES.md"), lines.join("\n")],
  [
    join(root, "src", "app", "thirdPartyComponents.json"),
    JSON.stringify(
      components.map(({ name, version, license }) => ({ name, version, license })),
      null,
      2,
    ) + "\n",
  ],
];
let stale = false;
for (const [file, content] of outputs) {
  const current = existsSync(file) ? readFileSync(file, "utf8").replace(/\r\n/g, "\n") : "";
  if (current === content) continue;
  if (check) {
    console.error(`${file} is out of date. Run node scripts/third-party-licenses.mjs.`);
    stale = true;
  } else {
    writeFileSync(file, content);
    console.log(`wrote ${file}`);
  }
}
const missing = components.filter((c) => c.files.length === 0);
console.log(
  `${components.length} components, ${texts.size} distinct license texts, ${missing.length} without a license file: ${missing.map((c) => c.name).join(", ") || "none"}`,
);
if (stale) process.exit(1);
